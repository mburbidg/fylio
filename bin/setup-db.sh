#!/usr/bin/env bash

docker exec -i --user postgres fylio-db-1 createdb fyliodb

docker exec -i --user postgres fylio-db-1 psql fyliodb -a  <<__END
create user fylio_role password 'lacinia';
grant create on schema public to fylio_role;
__END

docker exec -i fylio-db-1 psql -Ufylio_role fyliodb -a <<__END
drop table if exists users;
drop table if exists courses;

create table users (
  user_id int generated by default as identity primary key,
  first_name text not null,
  last_name text not null,
  email text not null,
  password text not null);

create table courses (
  course_id int generated by default as identity primary key,
  name text not null,
  location text not null);

create table registrations (
  user_id int references users(user_id),
  course_id int references courses(course_id),
  primary key (user_id, course_id));

insert into users (user_id, first_name, last_name, email, password) values
  (1234, 'Lonnie', 'Millett', 'lmillett@gmail.com', 'aaa'),
  (1235, 'John', 'Doe', 'johndoe@gmail.com', 'bbb'),
  (1236, 'Judy', 'Martin', 'judymartin@gmail.com', 'yyy'),
  (1237, 'Michael', 'Burbidge', 'mburbidg@gmail.com', 'xxx');

alter table users alter column user_id restart with 1300;

insert into courses (course_id, name, location) values
  (200, 'Computer Science 101', 'TMCB 1113'),
  (201, 'Computer Science 102', 'TMCB 1002'),
  (202, 'American Heritage 100', 'Joseph Smith Building 201'),
  (203, 'Algebra 201', 'Remote'),
  (204, 'Religion 200', 'Joseph Smith Building 220');

alter table courses alter column course_id restart with 300;

insert into registrations (user_id, course_id) values
  (1234, 200),
  (1235, 201),
  (1235, 204),
  (1237, 200),
  (1237, 203);
__END
